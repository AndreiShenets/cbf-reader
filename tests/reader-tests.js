  updateProgress();
  await settled();
  finishReload();
  await settled();
  source.prepare = originalPrepare;
  assert(!sections.get(0).images[0].hasAttribute('src'), 'late back-scroll reload cannot reattach released image URLs');
  assert($('notice').hidden, 'back-scroll cleanup does not report false image failures');
  scrollTo(0, sections.get(0).node.offsetTop);
  updateProgress();
  await source.queue;
  await settled();
  assert(current === 0 && images[0].src.startsWith('blob:'), 'scrolling back reloads released images');
  await images[0].decode();
  images[0].dispatchEvent(new Event('error'));
  assert($('notice').hidden && !images[0].classList.contains('failed'), 'late errors do not mark a successfully loaded image as broken');
  const validUrl = images[0].src;
  const invalidUrl = URL.createObjectURL(new Blob(['not an image']));
  const realImageError = new Promise(resolve => images[0].addEventListener('error', resolve, {once: true}));
  images[0].src = invalidUrl;
  await realImageError;
  assert(!$('notice').hidden && images[0].classList.contains('failed'), 'genuinely invalid images still report an error');
  images[0].src = validUrl;
  await images[0].decode();
  await settled();
  assert(!images[0].classList.contains('failed'), 'successful reload clears the failed-image marker');
  URL.revokeObjectURL(invalidUrl);
  $('notice').hidden = true;
